"""Zeek policy-script renderer — ATT&CK-for-ICS NOTICE companion to the Zeek signature renderer.

The signature renderer (zeek.py) emits byte-level .sig signatures. This renderer emits the second Zeek
mode the project wanted: a .zeek POLICY script that turns a raw signature hit into a categorized,
ATT&CK-for-ICS NOTICE (ACID-style), keyed on each check's `mitre_attack_id`. It hooks the stable Zeek
BASE event `signature_match` for THIS check+mode's signature id and raises a per-check Notice::Type —
so a Malcolm/Hedgehog/Corelight deployment gets a labelled ICS notice (technique + protocol + CVE)
instead of a bare signature log line, with no guessed field conditions.

WHY signature_match and not the ICSNPP protocol events directly: a field-level detection (e.g. "Modbus
function_code == 6" or "MBAP protocol-id != 0") needs to know WHICH parsed protocol field each check
targets — and that lives only in the prose `broad.description` of our checks, not as structured data
(the Modbus checks alone split across function-code, protocol-id-field, and unit-id-field triggers). A
generic ICSNPP-event renderer would therefore mislabel most checks. Hooking `signature_match` reuses the
byte pattern the .sig already encodes (correct by construction) and only ADDS the technique/CVE
labelling. True ICSNPP-event field-level detection is a later step gated on a structured
`protocol_event` block being added to `detection_hints` (zeek_event + condition) per check.

Output pairs with zeek/<check_id>.<mode>.sig — load both (@load-sigs the .sig, @load this .zeek).
These are passive DETECTION notices, never inline blocking (same posture as the other renderers).
"""
from __future__ import annotations

import re
from typing import Optional

from core.check_loader import CheckRecord
from core.renderers.zeek import _sig_id, _stable_sid


def _notice_type(check_id: str, mode: str) -> str:
    base = re.sub(r"[^0-9a-zA-Z]+", "_", check_id).strip("_")
    return f"ICS_{mode}_{base}"


def output_filename(record: CheckRecord, mode: str) -> Optional[str]:
    # Readable, collision-free: one policy script per check+mode (matches the default scheme, but the
    # ext is fixed to .zeek regardless of the DISPATCH ext so a mixed zeek/zeek-policy run is unambiguous).
    return f"{record.check_id}.{mode}.zeek"


def render(record: CheckRecord, mode: str) -> Optional[str]:
    if not record.has_hints:
        return None
    block = record.detection_hints.get(mode)
    if not block or not block.get("patterns"):
        return None  # no signature for this mode -> nothing to raise a NOTICE on
    # Stay paired with the .sig renderer: if zeek.py emits no signature (all patterns generic or
    # stream-unsafe) there is no signature_match to hook, so raise no NOTICE either.
    from core.pattern_quality import usable_patterns
    if not usable_patterns(block["patterns"], stream=True):
        return None

    hints = record.detection_hints
    sid = _stable_sid(record.check_id, mode)
    sig_id = _sig_id(record.check_id, mode, sid)
    notice_type = _notice_type(record.check_id, mode)

    app_protocol = hints.get("app_protocol") or "ics"
    mitre = hints.get("mitre_attack_id")
    sub = f"{app_protocol}/{mitre}" if mitre else app_protocol
    cve = f" ({record.cve_id})" if record.cve_id else ""
    msg = f"ICS-SCANNER {mode.upper()} - {record.check_id}{cve}".replace('"', "'")

    meta = [f"# detection_gen_mode: {mode}", f"# check_id: {record.check_id}", f"# app_protocol: {app_protocol}"]
    if mitre:
        meta.append(f"# mitre_attack_id: {mitre}")
    if record.cve_id:
        meta.append(f"# cve: {record.cve_id}")
    if getattr(record, "can_id", None):
        meta.append(f"# can_id: {record.can_id}")

    return (
        f"# Auto-generated by detection-gen (ATT&CK-for-ICS NOTICE companion) from icsScanner check "
        f"'{record.check_id}'\n"
        f"# Pairs with the Zeek signature zeek/{record.check_id}.{mode}.sig — load both (@load-sigs the\n"
        f"# .sig, @load this script). Raises a categorized NOTICE when that signature matches.\n"
        + "\n".join(meta) + "\n"
        "@load base/frameworks/notice\n\n"
        "module ICS_Scanner;\n\n"
        "export {\n"
        f"\tredef enum Notice::Type += {{ {notice_type} }};\n"
        "}\n\n"
        "event signature_match(state: signature_state, msg: string, data: string)\n"
        "\t{\n"
        f"\tif ( state$sig_id != \"{sig_id}\" )\n"
        "\t\treturn;\n"
        "\tNOTICE([$note=ICS_Scanner::" + notice_type + ",\n"
        f"\t        $msg=\"{msg}\",\n"
        f"\t        $sub=\"{sub}\",\n"
        "\t        $conn=state$conn,\n"
        f"\t        $identifier=cat(state$conn$uid, \"{record.check_id}\", \"{mode}\")]);\n"
        "\t}\n"
    )
