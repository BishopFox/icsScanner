"""Sigma rule renderer. Verified against sigmahq.io's official specification (see
../../lab-notes/format-research.md) — not general knowledge.

Sigma is a log-detection format, not a network-packet-capture format: its `logsource`/`detection`
model describes structured LOG FIELDS (e.g. a firewall or IDS log's own fields), not raw bytes on
the wire. This is a real, honest limitation for icsScanner's checks, most of which describe raw
TCP/UDP payload bytes rather than a specific log source's field names — there is no ICS/OT
`product` value in Sigma's own taxonomy either (see format-research.md). This renderer's approach:
emit a `category: network` / generic `product: firewall` (or the more specific `zeek`, if a
protocol has a well-known Zeek log — not assumed here) rule whose `detection.selection` matches
against a generic raw-payload-style field name (`payload|contains`), which several Sigma backends
targeting network logs (e.g. Zeek/Suricata-eve.json-shaped) do support — but this is explicitly
a best-effort mapping, not a first-class fit, and is documented as such in every rule's own
`description` field via a fixed disclaimer suffix.

IMPORTANT LESSON (caught while building the pilot, 2026-08-21): this renderer builds a real
Python dict and hands it to yaml.safe_dump() — it does NOT hand-format YAML text via string
interpolation. A first version did the latter, and it silently produced INVALID DETECTION LOGIC:
a `detection_hints` byte pattern containing literal CR/LF bytes (e.g. the SEL relay check's
"ACC\\r\\nOTTER\\r\\n" probe), when string-interpolated directly into a single-quoted YAML
scalar, got folded by YAML's own line-folding rules into "ACC OTTER " — the file still PARSED
as valid YAML (no error raised), but the detection pattern was silently wrong, would never match
the real attack traffic it was meant to detect, and nothing would have flagged this short of
manually re-parsing and eyeballing the generated file's actual field value. Always build a real
dict/data structure and let a real YAML emitter handle escaping — never hand-format YAML text
containing untrusted/binary-ish string content.
"""

from __future__ import annotations

import uuid
from typing import Optional

import yaml

from core.check_loader import CheckRecord


class _NoAliasDumper(yaml.SafeDumper):
    """Disables YAML anchor/alias generation — a generated detection rule should never rely on
    a reader resolving `&anchor`/`*alias` references, which some downstream Sigma tooling does
    not support."""

    def ignore_aliases(self, data):
        return True


def _severity_to_level(record: CheckRecord) -> str:
    sev = (record.severity or "").lower()
    if "critical" in sev or "9." in sev or "10.0" in sev:
        return "critical"
    if "high" in sev or record.destructive:
        return "high"
    if "medium" in sev:
        return "medium"
    return "low"


def _pattern_to_selection(pattern: dict, index: int) -> tuple[str, dict]:
    key = "selection" if index == 0 else f"selection{index}"
    if "bytes" in pattern:
        decoded = pattern["bytes"].encode().decode("unicode_escape")
        return key, {"payload|contains": decoded}
    if "regex" in pattern:
        return key, {"payload|re": pattern["regex"]}
    return key, {}


def _stable_uuid(check_id: str, mode: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"detection-gen:{check_id}:{mode}"))


def render(record: CheckRecord, mode: str) -> Optional[str]:
    """mode: 'narrow' or 'broad'. Returns None if the check has no hints, or no patterns exist
    for the requested mode (e.g. Beckwith's comm-channel-unlocked check has an intentionally
    empty `broad.patterns` — no broader signature applies, and this function must not invent
    one to fill the gap)."""
    if not record.has_hints:
        return None
    block = record.detection_hints.get(mode)
    if not block or not block.get("patterns"):
        return None

    # Drop trivially-generic patterns (noise in any format). Sigma matches log fields, not a
    # reassembled stream, so the stream-unsafe gate does not apply here. See core/pattern_quality.py.
    from core.pattern_quality import usable_patterns
    selections = {}
    for i, pattern in enumerate(usable_patterns(block["patterns"])):
        key, sel = _pattern_to_selection(pattern, i)
        if sel:
            selections[key] = sel
    if not selections:
        return None

    description = (
        f"{block.get('description', record.description)} "
        f"[Auto-generated by detection-gen from icsScanner check '{record.check_id}'. Sigma has "
        f"no ICS/OT-specific logsource product — this rule targets a generic raw-payload field "
        f"('payload'), which requires a backend/log pipeline that actually exposes one (e.g. a "
        f"Zeek conn.log-derived payload field, or a Suricata eve.json alert payload) — verify "
        f"field-name compatibility with your actual log source before deploying.]"
    )

    condition = "selection" if len(selections) == 1 else "1 of selection*"

    tags = [f"detection_gen.mode.{mode}"]
    if record.fingerprint_precondition and record.fingerprint_precondition.get("vendor"):
        tags.append("vendor." + record.fingerprint_precondition["vendor"].lower().replace(" ", "_"))

    references = []
    if record.cve_id:
        references.append(f"CVE: {record.cve_id}")
    elif record.can_id:
        references.append(f"CAN: {record.can_id}")

    rule = {
        "title": f"{record.check_id} ({mode})"[:256],
        "id": _stable_uuid(record.check_id, mode),
        "status": "experimental",
        "description": description,
        "author": "detection-gen (auto-generated, review before use)",
        "logsource": {"category": "network", "product": "firewall"},
        "detection": {**selections, "condition": condition},
        "level": _severity_to_level(record),
        "tags": tags,
    }
    if references:
        rule["references"] = references

    return yaml.dump(rule, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=100)
